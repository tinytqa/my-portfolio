// Copies photos from /image/<folder> into /public/gallery/<folder> with clean
// file names and regenerates src/lib/gallery.js.
// Usage: node scripts/sync-gallery.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const srcDir = path.join(root, "image");
const outDir = path.join(root, "public", "gallery");
const manifestPath = path.join(root, "src", "lib", "gallery.js");

// Display order + labels. Folders not listed here are appended with their raw name.
const LABELS = {
  me: "Về tôi",
  badminton: "Cầu lông",
  running: "Chạy bộ",
  trekking: "Trekking",
};
// Preferred cover image per folder (original file name)
const COVERS = { me: "ẢNH CÁ NHÂN.JPG" };

const IMG_RE = /\.(jpe?g|png|webp|avif)$/i;

fs.rmSync(outDir, { recursive: true, force: true });

const folders = fs
  .readdirSync(srcDir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort((a, b) => {
    const order = Object.keys(LABELS);
    const ia = order.indexOf(a) === -1 ? 99 : order.indexOf(a);
    const ib = order.indexOf(b) === -1 ? 99 : order.indexOf(b);
    return ia - ib || a.localeCompare(b);
  });

const albums = folders.map((folder) => {
  let files = fs.readdirSync(path.join(srcDir, folder)).filter((f) => IMG_RE.test(f)).sort();
  const cover = COVERS[folder];
  if (cover && files.includes(cover)) files = [cover, ...files.filter((f) => f !== cover)];

  fs.mkdirSync(path.join(outDir, folder), { recursive: true });
  const photos = files.map((file, i) => {
    const name = `${String(i + 1).padStart(2, "0")}${path.extname(file).toLowerCase()}`;
    fs.copyFileSync(path.join(srcDir, folder, file), path.join(outDir, folder, name));
    return `/gallery/${folder}/${name}`;
  });

  return { id: folder, label: LABELS[folder] ?? folder, photos };
});

const banner = "// Auto-generated by scripts/sync-gallery.mjs — do not edit by hand.\n";
fs.writeFileSync(manifestPath, `${banner}export const ALBUMS = ${JSON.stringify(albums, null, 2)};\n`);

